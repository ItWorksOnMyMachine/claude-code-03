// Silence console warnings in tests
const originalWarn = console.warn;
console.warn = (...args) => {
  if (
    typeof args[0] === 'string' &&
    args[0].includes('Material-UI') ||
    args[0].includes('MUI')
  ) {
    return;
  }
  originalWarn.call(console, ...args);
};